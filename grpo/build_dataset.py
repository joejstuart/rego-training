def _load_phase61_tasks() -> list[dict]:
    records = []
    if not PHASE61_TASKS.exists():
        return records
    for task_dir in sorted(PHASE61_TASKS.iterdir()):
        if not task_dir.is_dir():
            continue
        meta_path = task_dir / "meta.json"
        result_path = task_dir / "result.json"
        if not meta_path.exists() or not result_path.exists():
            continue
        meta = json.loads(meta_path.read_text())
        result = json.loads(result_path.read_text())
        if result.get("status") != "pass":
            continue
        pkg = meta["package_name"]
        rule_path = task_dir / f"{pkg}.rego"
        test_path = task_dir / f"{pkg}_test.rego"
        if not rule_path.exists() or not test_path.exists():
            continue

        test_code = test_path.read_text()
        task_id = meta["task_id"]

        # Replace smoke-only tests with self-contained functional tests
        if "test_module_loads" in test_code and test_code.count("test_") == 1:
            if task_id in _HELPER_FUNCTIONAL_TESTS:
                test_code = _HELPER_FUNCTIONAL_TESTS[task_id]

        records.append({
            "task_id": task_id,
            "package_name": pkg,
            "task_type": meta.get("task_type", "deny_rule"),
            "rule_code": rule_path.read_text(),
            "test_code": test_code,
        })
    return records


def _extract_func_descriptions(code: str) -> list[dict]:
    """Extract exported function/rule names with their doc-comments from Rego code.

    Returns a list of dicts: {"name": "func(args)", "doc": "one-line description"}
    Only returns *exported* (non-underscore) symbols.
    """
    lines = code.split("\n")
    results: list[dict] = []
    seen: set[str] = set()
    for i, line in enumerate(lines):
        m = re.match(r"^([a-zA-Z]\w*)(\([^)]*\))?\s*(?::=|contains|if\b)", line)
        if not m:
            continue
        name = m.group(1)
        if name in {"package", "import", "default", "not", "deny"}:
            continue
        sig = f"{name}{m.group(2) or ''}"
        if name in seen:
            continue
        seen.add(name)
        # Gather preceding comment lines (skip regal ignore lines)
        comments: list[str] = []
        j = i - 1
        while j >= 0 and lines[j].startswith("#") and "regal ignore" not in lines[j]:
            comments.insert(0, lines[j].lstrip("# ").strip())
            j -= 1
        doc = " ".join(comments).strip()[:150] if comments else ""
        results.append({"name": sig, "doc": doc})
    return results


def _build_helper_description(pkg: str, funcs: list[dict]) -> str:
    """Build a concrete behavioral prompt for a helper module."""
    if not funcs:
        return f"Write a standalone Rego helper module in package `{pkg}`."

    # Build per-function descriptions
    parts: list[str] = []
    for f in funcs[:8]:
        if f["doc"]:
            parts.append(f"`{f['name']}` — {f['doc']}")
        else:
            parts.append(f"`{f['name']}`")

    func_list = "; ".join(parts)
    return (
        f"Write a Rego helper module in package `{pkg}`. "
        f"Do NOT write deny rules. "
        f"Implement the following exported functions/rules: {func_list}."
    )


def _build_deny_description(pkg: str, code: str) -> str:
    """Build a concrete behavioral prompt for a deny rule module."""
    # Extract deny message templates
    deny_msgs: list[str] = re.findall(r'msg\s*:=\s*sprintf\(\s*"([^"]+)"', code)
    if not deny_msgs:
        deny_msgs = re.findall(r'msg\s*:=\s*"([^"]+)"', code)

    if deny_msgs:
        conditions = "; ".join(
            f'"{m}"' for m in dict.fromkeys(deny_msgs)  # deduplicate, preserve order
        )
        return (
            f"Write Rego deny rules in package `{pkg}` that reject attestations. "
            f"The deny messages should cover: {conditions}."
        )
    return f"Write Rego deny rules in package `{pkg}` that validate pipelineRun attestations."


def _phase6_prompt_variants(task: dict) -> list[tuple[str, str]]:
    pkg = task["package_name"]
    rule_code = task.get("rule_code", "")

    if task["task_type"] == "helper_method":
        funcs = _extract_func_descriptions(rule_code)
        canonical = _build_helper_description(pkg, funcs)
        # Shorter variant using just function names
        names_only = ", ".join(f"`{f['name']}`" for f in funcs[:8])
        terse = (
            f"Create helper functions in package `{pkg}`: {names_only}. "
            f"No deny rules."
        ) if funcs else canonical
        # Behavior-focused variant
        behavior = (
            f"Implement reusable Rego helper code for package `{pkg}`. "
            f"Each exported function should have deterministic return behavior. "
            f"Do not produce deny rule output."
        )
        if funcs:
            behavior += f" Required exports: {names_only}."
        return [
            ("phase6_helper_canonical", canonical),
            ("phase6_helper_terse", terse),
            ("phase6_helper_behavior", behavior),
        ]

    # deny rule
    canonical = _build_deny_description(pkg, rule_code)
    return [
        ("phase6_canonical", canonical),
    ]


